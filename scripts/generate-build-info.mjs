import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const assets = [
  "./", "./index.html", "./styles.css", "./app.js", "./config.js", "./cheats-db.js",
  "./manifest.webmanifest", "./assets/icon-192.png", "./assets/icon-512.png", "./assets/apple-touch-icon.png",
  "./pixelgba-worker.js", "./loader.js", "./emulator.min.js", "./emulator.min.css", "./version.json",
  "./en-US.json", "./mgba.json", "./mgba-wasm.data", "./mgba-legacy-wasm.data",
  "./extract7z.js", "./extractzip.js", "./libunrar.js", "./libunrar.wasm",
  "./sw.js", "./check.html", "./SECURITY.md", "./docs/DEVICE_TEST_MATRIX.md", "./docs/CHEAT_PROVENANCE.md", "./LICENSE", "./THIRD_PARTY_NOTICES.md"
];
const hash = createHash("sha256");
for (const asset of assets.filter((name) => name !== "./")) {
  const filename = resolve(root, asset.slice(2));
  if (!existsSync(filename)) throw new Error(`Cannot generate build metadata: ${asset} is missing`);
  hash.update(asset).update("\0").update(readFileSync(filename)).update("\0");
}
const info = { id: hash.digest("hex").slice(0, 20), assets: [...assets, "./build-info.js"] };
const output = `/* Generated by scripts/generate-build-info.mjs; do not edit. */\nglobalThis.PIXELGBA_BUILD = Object.freeze(${JSON.stringify(info, null, 2)});\n`;
const target = resolve(root, "build-info.js");
if (process.argv.includes("--check")) {
  if (!existsSync(target) || readFileSync(target, "utf8") !== output) {
    console.error("build-info.js is stale; run npm run build:meta");
    process.exit(1);
  }
  console.log(`Build metadata is current (${info.id}).`);
} else {
  writeFileSync(target, output);
  console.log(`Wrote build-info.js (${info.id}).`);
}
